import { access, readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const projectRoot = resolve(import.meta.dirname, "..");
const catalogRoot = resolve(projectRoot, "public", "catalog");
const thumbRoot = resolve(projectRoot, "public", "catalog-thumbs");
const webRoot = resolve(projectRoot, "public", "catalog-web");
const imageManifestPath = resolve(projectRoot, "app", "data", "catalog-images.json");
const metaPath = resolve(projectRoot, "app", "data", "catalog-meta.json");
const metaModulePath = resolve(projectRoot, "app", "data", "catalog-meta.ts");
const writeMode = process.argv.includes("--write");

function fail(message) {
  throw new Error(`Catalogue maintenance check failed: ${message}`);
}

async function scanImages() {
  const directories = (await readdir(catalogRoot, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory() && /^bq\d{3}$/.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  const manifest = {};
  for (const slug of directories) {
    const files = (await readdir(resolve(catalogRoot, slug), { withFileTypes: true }))
      .filter((entry) => entry.isFile() && /^\d{2}_[a-z0-9_-]+\.jpg$/i.test(entry.name))
      .map((entry) => entry.name.replace(/\.jpg$/i, ""))
      .sort();
    if (files.length < 4) fail(`${slug} needs at least four useful JPG gallery images; found ${files.length}.`);
    if (files[0] !== "01_main") fail(`${slug} must start with 01_main.jpg.`);
    manifest[slug] = files;
  }
  if (!directories.length) fail("no bqNNN product image directories were found.");
  return manifest;
}

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

async function verifyGeneratedFile(path, expected, label) {
  let actual;
  try { actual = await readFile(path, "utf8"); } catch { fail(`${label} is missing; run npm run catalog:sync.`); }
  if (actual !== expected) fail(`${label} is stale; run npm run catalog:sync and review the generated diff.`);
}

const manifest = await scanImages();
const meta = { productCount: Object.keys(manifest).length };
const metaModule = `// Generated by npm run catalog:sync. Do not edit by hand.\nexport const productCount = ${meta.productCount};\n`;
if (writeMode) {
  await writeFile(imageManifestPath, stableJson(manifest), "utf8");
  await writeFile(metaPath, stableJson(meta), "utf8");
  await writeFile(metaModulePath, metaModule, "utf8");
} else {
  await verifyGeneratedFile(imageManifestPath, stableJson(manifest), "catalog-images.json");
  await verifyGeneratedFile(metaPath, stableJson(meta), "catalog-meta.json");
  await verifyGeneratedFile(metaModulePath, metaModule, "catalog-meta.ts");
}

const moduleNonce = writeMode ? `?catalog-sync=${Date.now()}` : "";
const [{ products, collections }, { productNameZh }] = await Promise.all([
  import(`../app/data/products.ts${moduleNonce}`),
  import(`../app/data/products-zh.ts${moduleNonce}`),
]);

const collectionSlugs = new Set(collections.map((collection) => collection.slug));
const codes = new Set(); const slugs = new Set(); const sourceModels = new Set();
for (const product of products) {
  if (!/^BQ\d{3}$/.test(product.code)) fail(`${product.code || "unknown product"} must use BQ plus three digits.`);
  if (product.slug !== product.code.toLowerCase()) fail(`${product.code} slug must be ${product.code.toLowerCase()}.`);
  if (codes.has(product.code) || slugs.has(product.slug)) fail(`${product.code} duplicates an existing code or slug.`);
  if (!String(product.sourceModel || "").trim()) fail(`${product.code} is missing its source model.`);
  if (sourceModels.has(product.sourceModel)) fail(`${product.code} reuses source model ${product.sourceModel}; confirm whether it is truly a separate style.`);
  codes.add(product.code); slugs.add(product.slug); sourceModels.add(product.sourceModel);
  for (const field of ["name", "shortDescription", "group", "upper", "sole", "size", "buyerFit"]) if (!String(product[field] || "").trim()) fail(`${product.code} is missing ${field}.`);
  for (const field of ["colors", "collections", "highlights", "confirmBeforeQuote", "images"]) if (!Array.isArray(product[field]) || !product[field].length) fail(`${product.code} needs a non-empty ${field} list.`);
  if (product.highlights.length < 2) fail(`${product.code} needs at least two evidence-led highlights.`);
  if (product.confirmBeforeQuote.length < 2) fail(`${product.code} needs at least two quotation confirmations.`);
  for (const slug of product.collections) if (!collectionSlugs.has(slug)) fail(`${product.code} uses unknown collection ${slug}.`);
  if (product.alibabaProductId && !/^\d{10,20}$/.test(product.alibabaProductId)) fail(`${product.code} has an invalid Alibaba product ID.`);
  const wideClaim = [product.name, product.shortDescription, product.group, product.buyerFit, ...product.highlights].join(" ");
  if (/\b(?:wide toe|wide-toe|roomy toe|roomy-toe)\b/i.test(wideClaim) && product.fitEvidence !== "wide_toe_verified") fail(`${product.code} uses a wide-toe claim without fitEvidence: wide_toe_verified.`);
  if (productNameZh(product) === product.name) fail(`${product.code} is missing a reviewed Chinese product name.`);
  const expectedImages = manifest[product.slug]?.map((name) => `/catalog/${product.slug}/${name}.jpg`) || [];
  if (JSON.stringify(product.images) !== JSON.stringify(expectedImages)) fail(`${product.code} image list does not match its source image directory.`);
}

const manifestSlugs = Object.keys(manifest);
if (products.length !== manifestSlugs.length) fail(`product records (${products.length}) and image directories (${manifestSlugs.length}) differ.`);
for (const slug of manifestSlugs) if (!slugs.has(slug)) fail(`${slug} has images but no product record.`);

if (!writeMode) {
  for (const [slug, images] of Object.entries(manifest)) {
    await access(resolve(thumbRoot, `${slug}.webp`)).catch(() => fail(`${slug} thumbnail is missing; run npm run images:build.`));
    for (const image of images) await access(resolve(webRoot, slug, `${image}.webp`)).catch(() => fail(`${slug}/${image}.webp is missing; run npm run images:build.`));
  }
}

console.log(`${products.length} product records, ${manifestSlugs.length} image folders and Chinese names are aligned${writeMode ? "; generated manifests updated" : "; derivatives present"}.`);
