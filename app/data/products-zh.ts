export function productNameZh(product: Product) {
  return names[product.code] || product.name;
}
export function colorZh(color: string) {
  return colors[color] || color;
}
export function factZh(value: string) {
  return phrases.reduce(
    (text, [pattern, replacement]) => text.replace(pattern, replacement),
    value,
  );
}
export function closureZh(value: Product["closure"]) {
  return value === "Slip-On" ? "套穿" : "系带";
}
export function productSummaryZh(product: Product) {
  const fit = ["BQ001", "BQ002", "BQ031"].includes(product.code)
    ? "已核实宽鞋头结构"
    : `${closureZh(product.closure)}结构`;
  return `${product.sourceModel}款，${fit}，提供${product.colors.length}种已整理颜色方向，适合作为海外B2B选款、样品和报价讨论的候选产品。`;
}
export function buyerFitZh(product: Product) {
  if (/Kids/i.test(product.group)) return "儿童鞋进口商、批发商及渠道买家";
  if (/Men/i.test(product.group)) return "男士休闲鞋进口商和批发买家";
  if (["BQ001", "BQ002", "BQ031"].includes(product.code))
    return "宽鞋头舒适鞋进口商、批发商、品牌买家和线上渠道买家";
  if (/Athletic/i.test(product.group))
    return "运动休闲鞋进口商、批发商和线上卖家";
  return "休闲步行鞋进口商、批发商、线上卖家和品牌买家";
}
